import assert from "node:assert/strict";
import { readFileSync } from "node:fs";
import test from "node:test";

test("admin today can turn on push alerts and open the right tab", () => {
  const today = readFileSync("src/admin-app/today-dashboard.js", "utf8");
  const card = readFileSync("src/admin-app/admin-push.js", "utf8");
  const controller = readFileSync("src/admin-app/admin-controller.js", "utf8");
  const sw = readFileSync("sw.js", "utf8");
  const manifest = JSON.parse(readFileSync("site.webmanifest", "utf8"));
  const pwa = readFileSync("pwa.js", "utf8");
  assert.match(today, /AdminPushCard/);
  assert.match(card, /Turn on alerts/);
  assert.match(card, /Alerts are on for this phone/);
  assert.match(card, /applicationServerKey/);
  assert.match(card, /\/admin\/push/);
  assert.match(controller, /queryTab === 'orders'/);
  assert.match(controller, /readAppRoute/);
  assert.match(controller, /queryTab === 'members'/);
  assert.match(controller, /queryTab === 'tee-signs'/);
  assert.match(sw, /const CACHE = "gvdg-club-v253"/);
  assert.match(sw, /new URL\("\/img\/icons\/app-icon-192\.png", self\.location\.origin\)/);
  assert.match(sw, /new URL\("\/img\/icons\/notification-badge\.png", self\.location\.origin\)/);
  assert.match(sw, /Brave draws its own lion/);
  assert.match(sw, /addEventListener\("push"/);
  assert.match(sw, /addEventListener\("notificationclick"/);
  assert.match(sw, /APP_WINDOW/);
  assert.match(sw, /appClients/);
  assert.match(sw, /A Chrome tab must not catch the tap/);
  assert.equal(manifest.launch_handler.client_mode, "navigate-existing");
  assert.match(pwa, /type: 'APP_WINDOW'/);
  assert.match(pwa, /display-mode: standalone/);
});
