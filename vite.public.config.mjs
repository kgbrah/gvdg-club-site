import { resolve } from "node:path";
import { fileURLToPath } from "node:url";

import { defineConfig } from "vite";

const root = fileURLToPath(new URL(".", import.meta.url));
const outDir = "public-app";

function publicChunkManifest() {
  return {
    name: "gvdg-public-chunk-manifest",
    generateBundle(_options, bundle) {
      const files = Object.values(bundle)
        .filter((item) => item.type === "chunk" && !item.isEntry)
        .map((chunk) => `${outDir}/${chunk.fileName}`)
        .sort();
      this.emitFile({
        type: "asset",
        fileName: "sw-chunks.js",
        source: "// Generated by vite.public.config.mjs. Public app screens that load on demand; sw.js precaches them.\n"
          + `self.GVDG_PUBLIC_CHUNKS = ${JSON.stringify(files, null, 2)};\n`,
      });
    },
  };
}

export default defineConfig({
  base: "./",
  plugins: [publicChunkManifest()],
  build: {
    outDir,
    emptyOutDir: true,
    sourcemap: true,
    modulePreload: false,
    rolldownOptions: {
      input: resolve(root, "src/public-app/main.js"),
      output: {
        entryFileNames: "public-app.js",
        chunkFileNames: "chunks/[name]-[hash].js",
        assetFileNames: "assets/[name]-[hash][extname]",
      },
    },
  },
});
